function generateCandles(basePrice: number, currentPrice: number, days: number = 30): Candle[] {
  const candles: Candle[] = [];
  const now = new Date();
  let price = basePrice;

  for (let i = days; i >= 1; i--) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];

    const dailyVolatility = price * 0.012;
    const open = Number((price + (Math.random() - 0.48) * dailyVolatility).toFixed(2));
    const high = Number((Math.max(open, price) + Math.random() * dailyVolatility).toFixed(2));
    const low = Number((Math.min(open, price) - Math.random() * dailyVolatility).toFixed(2));
    const close = Number((i === 1 ? currentPrice : low + Math.random() * (high - low)).toFixed(2));
    const volume = Math.floor(800000 + Math.random() * 2000000);

    candles.push({
      date: dateStr,
      open,
      high,
      low,
      close,
      volume,
    });
    price = close;
  }
  return candles;
}

